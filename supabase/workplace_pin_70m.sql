-- 기본 근무지 핀 이동 + 반경 150m → 70m
-- 앱이 출퇴근을 '정확한 위치'로만 판정하게 바뀌면서 반경을 좁힌다.
-- 기존 핀은 실제 출근 기록이 모이는 지점에서 약 33m 벗어나 있었다. 새 좌표는
-- 이 근무지 150m 안 출근 기록(2026-04~10, 170건)의 위도·경도 중앙값.
-- 그 기준으로 2026-08 이후 출근의 86%가 70m 안(50m면 75%).
--
-- 여러 번 실행해도 안전(idempotent). 관리자가 앱에서 지운 경우엔 아무 일도 안 한다.

update public.workplaces
   set lat = 37.5616433,
       lng = 126.8288792,
       radius = 70
 where id = 'wp_default';
